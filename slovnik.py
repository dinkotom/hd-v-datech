def columns(name):
    d = DATASETS.get(name, {})
    if 'stejne_jako' in d:
        d = DATASETS[d['stejne_jako']]
    return d.get('sloupce', {})


def describe(name, col):
    cols = columns(name)
    if col in cols:
        return cols[col]
    if col.endswith('_na_obyv') and col[:-8] in cols:
        base = col[:-8]
        div = 'obyv_31_12' if base.startswith(('ucet', 'penize', 'kratk', 'dlouh', 'uvery')) else 'obyv_1_7'
        return f'`{base}` na obyvatele (děleno `{div}`). Kč.'
    return None
